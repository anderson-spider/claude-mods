// SessionStart: reuse generated declarations only when the main checkout has this host's version.
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const LIMIT_MS = 750;
const rootDir = fileURLToPath(new URL("../", import.meta.url));

function within(root, path) {
  const rel = relative(root, path);
  return rel === "" || (rel !== ".." && !rel.startsWith(`..${sep}`) && !isAbsolute(rel));
}

// Reject symlinks in every destination component, including existing `types`.
function safeDestination(root, path) {
  if (!within(root, path)) return false;
  for (let part = path; within(root, part); part = dirname(part)) {
    if (lstatSync(part, { throwIfNoEntry: false })?.isSymbolicLink()) return false;
    if (part === root) break;
  }
  return true;
}

// Source snapshots must be ordinary files/directories, not links to mutable or external data.
function ordinaryTree(path) {
  const stat = lstatSync(path);
  if (stat.isFile()) return true;
  if (!stat.isDirectory()) return false;
  return readdirSync(path).every((name) => ordinaryTree(join(path, name)));
}

function complete(source, version, plugin, main, root) {
  if (!existsSync(source) || !ordinaryTree(source)) return false;
  const config = JSON.parse(readFileSync(join(source, "tsconfig.json"), "utf8"));
  const types = config.compilerOptions?.types;
  if (!Array.isArray(types) || !["claude-code", "claude-code-tools", "claude-code-mcp"].every((name) => types.includes(name))) return false;
  for (const name of types) {
    if (typeof name !== "string" || !/^[a-zA-Z0-9_-]+$/.test(name) || !existsSync(join(source, name, "index.d.ts")) || !lstatSync(join(source, name, "index.d.ts")).isFile()) return false;
  }
  if (!readFileSync(join(source, "claude-code", "index.d.ts"), "utf8").startsWith(`// Written by Claude Code ${version}.\n`)) return false;
  const current = JSON.parse(readFileSync(join(root, "plugins", plugin, ".claude-plugin", "plugin.json"), "utf8"));
  const original = JSON.parse(readFileSync(join(main, "plugins", plugin, ".claude-plugin", "plugin.json"), "utf8"));
  const dependencies = current.dependencies ?? {};
  if (JSON.stringify(dependencies) !== JSON.stringify(original.dependencies ?? {})) return false;
  // A dependent's cached contracts are usable only when its local contracts still match.
  for (const name of Object.keys(dependencies)) {
    if (!/^[a-zA-Z0-9_-]+$/.test(name)) return false;
    const contract = join(root, "plugins", name, "types", "index.d.ts");
    const previous = join(main, "plugins", name, "types", "index.d.ts");
    if (!existsSync(contract) || !existsSync(previous) || readFileSync(contract, "utf8") !== readFileSync(previous, "utf8")) return false;
    if (!types.includes(name) || readFileSync(join(source, name, "index.d.ts"), "utf8") !== readFileSync(previous, "utf8")) return false;
  }
  return true;
}

function candidates(root, main) {
  if (!isAbsolute(main) || resolve(main) === resolve(root) || !safeDestination(root, join(root, "plugins"))) return [];
  return readdirSync(join(root, "plugins"), { withFileTypes: true }).filter((entry) => entry.isDirectory()).map((entry) => entry.name).filter((plugin) => {
    try {
      const parent = join(root, "plugins", plugin, ".claude-plugin");
      const target = join(parent, "types");
      return safeDestination(root, target) && !lstatSync(target, { throwIfNoEntry: false }) && existsSync(join(main, "plugins", plugin, ".claude-plugin", "types"));
    } catch { return false; }
  });
}

export function reusePluginTypes(root, main, version) {
  const copied = [];
  let available;
  try { available = candidates(root, main); } catch { return copied; }
  for (const plugin of available) {
    const parent = join(root, "plugins", plugin, ".claude-plugin");
    const target = join(parent, "types");
    const source = join(main, "plugins", plugin, ".claude-plugin", "types");
    let staging;
    try {
      if (!complete(source, version, plugin, main, root)) continue;
      if (!safeDestination(root, target) || lstatSync(target, { throwIfNoEntry: false })) continue;
      mkdirSync(parent, { recursive: true });
      staging = mkdtempSync(join(parent, ".types-"));
      cpSync(source, staging, { recursive: true, force: false, errorOnExist: false });
      if (!complete(staging, version, plugin, main, root) || !safeDestination(root, target) || existsSync(target)) continue;
      renameSync(staging, target);
      staging = undefined;
      copied.push(plugin);
    } catch {
      // A missing/partial cache is best regenerated by the explicit plugins:types task.
    } finally {
      try { if (staging) rmSync(staging, { recursive: true, force: true }); } catch { /* Do not fail SessionStart. */ }
    }
  }
  return copied;
}

export function bootstrap(root = rootDir, run = spawnSync) {
  try {
    const git = run("git", ["worktree", "list", "--porcelain"], { cwd: root, encoding: "utf8", timeout: LIMIT_MS });
    const main = git.status === 0 ? git.stdout?.match(/^worktree (.+)$/m)?.[1] : undefined;
    if (!main || !candidates(root, main).length) return [];
    const cli = run("claude", ["--version"], { cwd: root, encoding: "utf8", timeout: LIMIT_MS });
    const version = cli.status === 0 ? cli.stdout?.match(/^(\S+) \(Claude Code\)/)?.[1] : undefined;
    return version ? reusePluginTypes(root, main, version) : [];
  } catch {
    return [];
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const plugin of bootstrap()) console.log(`Reused typings for plugins/${plugin}`);
}
