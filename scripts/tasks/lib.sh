# Sourced by the task scripts: which `claude` and `tsc` a task runs.

# The node_modules/.bin that holds the pinned tools: this checkout's, else the main checkout's, since a fresh worktree
# has no node_modules until `npm ci` runs in it. Empty when neither has them.
pinned_bin() {
  local main
  main=$(git worktree list --porcelain 2>/dev/null | sed -n '1s/^worktree //p')
  for dir in "$PWD" ${main:+"$main"}; do
    if [ -x "$dir/node_modules/.bin/claude" ] && [ -x "$dir/node_modules/.bin/tsc" ]; then echo "$dir/node_modules/.bin"; return 0; fi
  done
  return 0
}

# Checks run with the CLI and TypeScript package.json pins, as CI does; without them the task stops rather than
# silently using another claude.
use_pinned_tools() {
  local bin
  bin=$(pinned_bin)
  [ -n "$bin" ] || { echo "the pinned tools are not installed: run npm ci" >&2; exit 1; }
  PATH="$bin:$PATH"
}

# Typings and installed plugins belong to the Claude Code you run sessions with, so these tasks use that claude, not
# the pinned one `npm run` puts first on PATH.
use_own_claude() {
  PATH=$(printf '%s' "$PATH" | tr ':' '\n' | grep -v '/node_modules/\.bin$' | paste -sd: -)
  command -v claude >/dev/null || { echo "claude is not on PATH outside node_modules: install Claude Code" >&2; exit 1; }
}

# Typings for each plugin folder given that has none, as a fresh worktree lacks them: copied from the same plugin in
# the main checkout (they depend only on the Claude Code version that wrote them), else generated by plugins:types in
# one session. A plugin left without them fails tsc with the usual missing-module errors.
ensure_typings() {
  local main d missing=()
  main=$(git worktree list --porcelain 2>/dev/null | sed -n '1s/^worktree //p')
  for d in "$@"; do
    [ -f "${d}.claude-plugin/types/tsconfig.json" ] && continue
    if [ -n "$main" ] && [ "$main" != "$PWD" ] && [ -f "$main/${d}.claude-plugin/types/tsconfig.json" ]; then
      echo "==> typings for ${d%/} copied from $main"
      cp -R "$main/${d}.claude-plugin/types" "${d}.claude-plugin/" || true
    else
      missing+=("$(basename "$d")")
    fi
  done
  if [ "${#missing[@]}" -gt 0 ]; then
    echo "==> generating typings for ${missing[*]}"
    bash scripts/tasks/plugins-types.sh "${missing[@]}" || true
  fi
}

# A plugin named on the command line: lowercase words joined by hyphens, with a folder under plugins/.
require_plugin() {
  [[ "$1" =~ ^[a-z][a-z0-9-]*$ && -d "plugins/$1" ]] || { echo "no such plugin: $1" >&2; exit 1; }
}
