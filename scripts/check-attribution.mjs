// Fails when a pull request credits an AI tool: a co-author trailer, a session trailer or a "Generated with" line.
// Run: node scripts/check-attribution.mjs <base-ref>   (CI passes origin/<base branch>; PR_TITLE and PR_BODY from env)
// It reads every commit message in <base-ref>..HEAD plus the title and body. A squash merge copies the commit
// trailers into main, so they must never reach the branch. `attributionFindings(text)` is the pure core.
import { execFileSync } from 'node:child_process'
import { realpathSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const AI = String.raw`claude|anthropic|codex|openai|chatgpt|gpt-?\d|copilot|gemini|cursor|devin|aider`

// Each pattern is tried on one line at a time.
const PATTERNS = [
  // A co-author trailer naming an AI tool or its address.
  new RegExp(String.raw`^\s*co-authored-by:.*(?<![a-z0-9])(?:${AI})(?![a-z0-9])`, 'i'),
  // Session or tool trailers some agents append.
  /^\s*(?:claude|codex)-session:/i,
  // "Generated with Claude Code", "Generated by Codex", "🤖 Generated with ...".
  new RegExp(String.raw`(?<![a-z])generated\s+(?:with|by)\b.*(?<![a-z0-9])(?:${AI})(?![a-z0-9])`, 'i'),
  /🤖/u,
]

/** The lines of `text` that credit an AI tool, trimmed, in order. */
export function attributionFindings(text) {
  return String(text ?? '')
    .split(/\r?\n/)
    .filter(line => PATTERNS.some(pattern => pattern.test(line)))
    .map(line => line.trim())
}

/** One error line per finding; `sources` is a list of `{ label, text }`. */
export function attributionErrors(sources) {
  return sources.flatMap(({ label, text }) => attributionFindings(text).map(line => `${label}: ${line}`))
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const base = process.argv[2]

  if (!base) {
    console.error('usage: node scripts/check-attribution.mjs <base-ref>')
    process.exit(2)
  }

  const log = execFileSync('git', ['log', '--format=%h%x00%B%x1e', `${base}..HEAD`], { encoding: 'utf8' })
  const commits = log
    .split('\x1e')
    .map(entry => entry.replace(/^\n/, ''))
    .filter(Boolean)
    .map(entry => {
      const [sha, message] = entry.split('\0')
      return { label: `commit ${sha}`, text: message }
    })
  const errors = attributionErrors([
    ...commits,
    { label: 'PR title', text: process.env.PR_TITLE },
    { label: 'PR body', text: process.env.PR_BODY },
  ])

  if (errors.length > 0) {
    console.error('AI attribution is not allowed in commits, PR titles or PR bodies; remove these lines (reword the commits on your branch):')
    for (const error of errors) console.error(`  ${error}`)
    process.exit(1)
  }

  console.log(`no AI attribution in ${commits.length} commit(s), the PR title or body`)
}
