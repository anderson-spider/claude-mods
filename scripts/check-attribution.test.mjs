import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { attributionErrors, attributionFindings, withoutHostFooter } from "./check-attribution.mjs";

const script = fileURLToPath(new URL("./check-attribution.mjs", import.meta.url));

test("AI co-author, session and generated-with lines are found, whatever their case", () => {
  const lines = [
    "Co-authored-by: Claude <noreply@anthropic.com>",
    "Co-Authored-By: Claude Opus 5 (1M context) <noreply@anthropic.com>",
    "co-authored-by: Codex <codex@openai.com>",
    "Co-authored-by: GitHub Copilot <copilot@github.com>",
    "Claude-Session: https://claude.ai/code/session_x",
    "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
    "Generated with Codex",
    "_Generated by ChatGPT_",
  ];

  for (const line of lines) assert.deepEqual(attributionFindings(`feat: x\n\nBody.\n\n${line}\n`), [line], line);
});

test("human co-authors and ordinary mentions of the plugins pass", () => {
  const text = [
    "feat(chatgpt): ask ChatGPT from a Claude Code session",
    "",
    "The codex-computer-use helper now generates the socket path.",
    "Generated with mise run plugin:new.",
    "Co-authored-by: Ana Souza <ana@example.com>",
    "<!-- claude-projects-attribution: {\"github_login\":\"anderson-spider\"} -->",
  ].join("\n");

  assert.deepEqual(attributionFindings(text), []);
  assert.deepEqual(attributionFindings(undefined), []);
});

test("each error names where the line was found", () => {
  const errors = attributionErrors([
    { label: "commit abc1234", text: "fix: y\n\nCo-authored-by: Claude <noreply@anthropic.com>" },
    { label: "PR title", text: "fix: y" },
    { label: "PR body", text: "## Summary\n\n🤖 Generated with Claude Code" },
  ]);

  assert.deepEqual(errors, [
    "commit abc1234: Co-authored-by: Claude <noreply@anthropic.com>",
    "PR body: 🤖 Generated with Claude Code",
  ]);
});

test("only the cloud host's trailing footer is dropped from a body; the same line elsewhere still counts", () => {
  const body = "## Summary\n\nText.\n";
  const footer = "\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01Eo3ZZHnyJCeaAosBY3MWBX)_";

  assert.deepEqual(withoutHostFooter(body + footer), { text: body, footer: true });
  assert.deepEqual(withoutHostFooter(body + "\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"), { text: body, footer: true });
  assert.deepEqual(withoutHostFooter(body), { text: body, footer: false });
  assert.deepEqual(withoutHostFooter(undefined), { text: "", footer: false });

  const midway = footer + "\n\nMore text.";
  assert.equal(withoutHostFooter(midway).footer, false);
  assert.equal(attributionFindings(withoutHostFooter(midway).text).length, 1);
  assert.equal(attributionFindings(withoutHostFooter(body + "🤖 Generated with [Claude Code](https://claude.com/claude-code)" + footer).text).length, 1);
});

test("the script reads the branch's commits and the PR title and body, and fails on any attribution", () => {
  const dir = mkdtempSync(join(tmpdir(), "check-attribution-"));
  const git = (...args) => execFileSync("git", args, { cwd: dir, encoding: "utf8" });
  const run = (env = {}) =>
    spawnSync(process.execPath, [script, "base"], { cwd: dir, encoding: "utf8", env: { ...process.env, PR_TITLE: "", PR_BODY: "", ...env } });

  try {
    git("init", "-q");
    git("-c", "user.name=t", "-c", "user.email=t@example.com", "commit", "-q", "--allow-empty", "-m", "chore: base\n\nCo-authored-by: Claude <noreply@anthropic.com>");
    git("branch", "base");
    git("-c", "user.name=t", "-c", "user.email=t@example.com", "commit", "-q", "--allow-empty", "-m", "feat: clean");

    // The base's own history is not this PR's.
    assert.equal(run().status, 0);
    assert.equal(run({ PR_BODY: "🤖 Generated with [Claude Code](https://claude.com/claude-code)" }).status, 1);
    assert.equal(run({ PR_TITLE: "feat: x (Generated by Codex)" }).status, 1);
    const footed = run({ PR_BODY: "## Summary\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_x)_" });
    assert.equal(footed.status, 0);
    assert.match(footed.stdout, /footer the Claude Code cloud host appends/);

    git("-c", "user.name=t", "-c", "user.email=t@example.com", "commit", "-q", "--allow-empty", "-m", "fix: y\n\nCo-Authored-By: Claude <noreply@anthropic.com>");
    const failed = run();
    assert.equal(failed.status, 1);
    assert.match(failed.stderr, /commit [0-9a-f]+: Co-Authored-By: Claude <noreply@anthropic.com>/);
    assert.equal(spawnSync(process.execPath, [script], { cwd: dir }).status, 2);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
